/*
================================================
دالة البحث عن معرفة الدرس
================================================
*/

function getPhysicsKnowledge(lesson) {

    if (!lesson) {
        return null;
    }

    if (PHYSICS_KNOWLEDGE[lesson]) {
        return PHYSICS_KNOWLEDGE[lesson];
    }

    const normalizedLesson =
        lesson.trim().toLowerCase();

    for (
        const key
        of Object.keys(PHYSICS_KNOWLEDGE)
    ) {

        if (
            key.trim().toLowerCase()
            === normalizedLesson
        ) {

            return PHYSICS_KNOWLEDGE[key];

        }

    }

    return null;

}


